async function upload(acc, kind) {
  const bytes = pdf(kind);
  const meta = { kind, fileName: `${kind.replace(/_/g, '-')}.pdf`, sizeBytes: bytes.length, sniffedMime: 'application/pdf' };
  const { documentId } = service.checkUpload(acc, meta);
  await mkdir(uploadsDir, { recursive: true, mode: 0o700 });
  const target = join(uploadsDir, documentId);
  await writeFile(`${target}.part`, bytes, { mode: 0o600 });
  await rename(`${target}.part`, target);
  store.pendingSha.set(documentId, createHash('sha256').update(bytes).digest('hex'));
  service.recordUpload(acc, meta, documentId);
  return documentId;
}

/** Copy the sample catalogue, orders and finances to this seller, if they have none yet. */
function importBusinessData(acc, certDocId) {
  const ws = _internal.getDb();
  if (ws.products.some((p) => p.sellerId === acc.sellerId)) return false;
  const sample = createSeed();
  const mine = (x) => x.sellerId === SELLER_A;
  const rekey = (x) => ({ ...x, sellerId: acc.sellerId });
  const existing = new Set(ws.products.map((p) => p.id));
  const products = sample.products.filter(mine).filter((p) => !existing.has(p.id)).map((p) => ({ ...rekey(p), ...(p.certificateId ? { certificateId: certDocId } : {}) }));
  store.transaction(() => {
    ws.products.push(...products);
    for (const k of ['orders', 'ledger', 'settlements', 'payoutRequests', 'reviews', 'adjustments', 'notifications']) ws[k].push(...sample[k].filter(mine).map(rekey));
    const seller = _internal.findSeller(acc.sellerId);
    const s = sample.sellers.find((x) => x.id === SELLER_A);
    Object.assign(seller, { brandColor: s.brandColor, bannerTagline: s.bannerTagline, workingHours: s.workingHours, holidays: s.holidays, fulfilment: s.fulfilment, notifications: s.notifications, staff: s.staff, payoutRequestsEnabled: true });
  });
  return true;
}

const results = [];
for (const spec of SELLERS) {
  const exists = db.prepare('SELECT id FROM users WHERE email = ? OR phone = ?').get(spec.account.email, spec.account.phone);
  if (exists) {
    // Never modify an existing account, except to add sample business data to a
    // seeded approved seller that has none (e.g. after an interrupted run).
    let note = 'skipped (already exists)';
    if (spec.importBusinessData) {
      const acc = rowToAccount(db.prepare('SELECT * FROM users WHERE id = ?').get(exists.id));
      const app0 = store.getApplicationByUser(acc.userId);
      const cert = app0 ? store.getOrganic(app0.id)?.documentId : null;
      if (app0?.status === 'approved' && importBusinessData(acc, cert)) note = 'existing account · added sample catalogue, orders and finances';
    }
    results.push({ email: spec.account.email, status: note });
    continue;
  }
  const passwordHash = await hashPassword(PASSWORD);
  const now = new Date().toISOString();
  const acc = store.transaction(() => {
    const id = newId('usr');
    db.prepare('INSERT INTO users (id, seller_id, full_name, email, phone, password_hash, email_verified_at, phone_verified_at, created_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)').run(
      id, newId('sel'), spec.account.fullName, spec.account.email, spec.account.phone, passwordHash, now, now, now,
    );
    store.audit({ actorType: 'system', actorId: 'seed-dev', action: 'account.created', applicationId: null });
    const a = rowToAccount(db.prepare('SELECT * FROM users WHERE id = ?').get(id));
    service.createForAccount(a);
    return a;
  });

  service.saveDraft(acc, spec.data, spec.stopAtStep ?? 8, null);
  if (spec.target === 'incomplete') {
    results.push({ email: acc.email, status: `incomplete (step ${spec.stopAtStep})` });
    continue;
  }
  service.saveBank(acc, { ...spec.bank, accountNumberConfirm: spec.bank.accountNumber });
  let certDocId = null;
  for (const kind of spec.docs) {
    const id = await upload(acc, kind);
    if (kind === 'organic_cert') certDocId = id;
  }
  const view = service.submit(acc, randomUUID());
  const appId = store.getApplicationByUser(acc.userId).id;

  if (spec.target === 'changes_requested') service.adminDecide(appId, 'request_changes', REVIEWER, spec.review.message, spec.review.items);
  if (spec.target === 'approved' || spec.target === 'suspended') {
    for (const d of store.listDocuments(appId)) service.adminReviewDocument(d.id, 'verified', REVIEWER, '');
    service.adminDecide(appId, 'approve', REVIEWER, '', []);
  }
  if (spec.target === 'suspended') service.adminDecide(appId, 'suspend', REVIEWER, spec.suspendMessage, []);
  const imported = spec.importBusinessData ? importBusinessData(acc, certDocId) : false;
  results.push({ email: acc.email, status: `${store.getApplicationById(appId).status} · ${view.referenceId}${imported ? ' · sample catalogue, orders and finances' : ''}` });
}

